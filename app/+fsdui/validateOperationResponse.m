function valid = validateOperationResponse(request,response)
%VALIDATEOPERATIONRESPONSE Bind canonically validated evidence to owner intent.
% Replay declarations/configuration only, reusing supplied canonical records.
% No forward solve, search, save, or mutable owner state is used here.
expected=operationBody(request,response);
assert(isequaln(response.project,expected.project) && ...
    isequaln(response.value,expected.value) && ...
    isequaln(response.compatibility(:),expected.compatibility(:)) && ...
    string(response.ledgerPolicy)==string(expected.ledgerPolicy), ...
    'fsd:ui:SemanticMismatch','Worker outcome differs from the pending operation.');
valid=true;
end
