function e=globalStaticEvidence(record,index)
%GLOBALSTATICEVIDENCE Read stored native state only; no solve or interpolation.
assert(record.engine=="GLOBAL_STATIC",'fsd:ui:GlobalInput','Global static result required.');
r=record.nativePayload.equilibrium;
e=struct('summary',["Native status: "+r.status;"Selected alternative: "+string(r.selectedIndex); ...
    "Root completeness: "+r.rootCompleteness;"Convergence does not certify stability."], ...
    'pose',{cell(0,3)},'corners',{cell(0,17)},'heights',{cell(0,2)},'attempts',{cell(0,5)}, ...
    'antiRollBars',{cell(0,7)},'details',strings(0,1));
for k=1:numel(r.attempts)
    a=r.attempts{k}; e.attempts(k,:)={k,a.solution.converged,char(a.solution.status),char(a.solution.stability),a.solution.jacobianReciprocalCondition};
end
if isempty(index) || ~isfinite(index), return; end
assert(isscalar(index) && index==fix(index) && index>=1 && index<=numel(r.alternatives), ...
    'fsd:ui:GlobalInput','Select a stored alternative.');
a=r.alternatives{index}; s=a.state;
if isfield(s,'antiRollBars')
    for k=1:numel(s.antiRollBars)
        b=s.antiRollBars{k};
        e.antiRollBars(k,:)={char(b.barIdentity.axleId),b.energy_J,b.twist_rad*180/pi,b.torque_Nm, ...
            b.resistance_N(1),b.resistance_N(2),char(b.status+" / K: "+b.tangentStatus)};
    end
    e.summary=[e.summary;"ARB energy [J]: "+s.antiRollBarEnergy_J+" | coupled internal forces; tire contact remains unilateral."];
end
e.summary=[e.summary;"Inspecting alternative "+index+" | converged="+a.converged+" | path feasible="+s.feasible; ...
    "Native admissibility/acceptance: "+a.status;"Stability: "+a.stability+" | ill-conditioned="+a.isIllConditioned];
names=["Heave","Pitch","Roll","Front axle load","Rear axle load","Left load","Right load", ...
    "Crossweight actual sum fraction","World Fz residual","World Mx residual","World My residual", ...
    "Gravity energy","Spring energy","Tire energy","Potential energy"];
units=["mm","deg","deg",repmat("N",1,4),"1","N","Nm","Nm",repmat("J",1,4)];
values=[s.heave_m*1000,rad2deg(s.pitch_rad),rad2deg(s.roll_rad),s.axleLoads_N',s.sideLoads_N', ...
    s.crossweightActualSumFraction,s.worldForceResidual_N,s.worldMomentResidual_Nm(1:2)', ...
    s.gravityEnergy_J,s.springEnergy_J,s.tireEnergy_J,s.potentialEnergy_J];
e.pose=[cellstr(names(:)),num2cell(values(:)),cellstr(units(:))];
for k=1:4
    c=s.corners{k}; t=c.tire;
    e.corners(k,:)={char(c.cornerId),c.wheelTravel_m*1000,c.wheelCenterWorld_m(1)*1000, ...
        c.wheelCenterWorld_m(2)*1000,c.wheelCenterWorld_m(3)*1000,c.damperCompression_m*1000, ...
        c.damperLength_m*1000,c.motionRatio,c.spring.springAxialForce_N,c.springWheelResistance_N, ...
        t.normalForce_N,t.tireCompression_m*1000,t.loadedRadius_m*1000,t.tireGap_m*1000, ...
        char(t.contactStatus),char(c.pathStatus),char(jsonencode(c.bounds))};
end
e.heights=[cellstr(s.rideHeightPointIds),num2cell(s.rideHeights_m*1000)];
e.details=["Generalized residual [N,Nm,Nm,N,N,N,N]: "+string(mat2str(s.residual',17)); ...
    "Total CG world [mm]: "+string(mat2str(s.totalCgWorld_m*1000,17)); ...
    "Sprung CG world [mm]: "+string(mat2str(s.sprungCgWorld_m*1000,17)); ...
    "Native solution: "+string(jsonencode(r.alternatives{index}))];
end
