function volume=packagingVolumeFixture(id,shape,dimensions,centre,R)
%PACKAGINGVOLUMEFIXTURE Explicit synthetic SI solids; NOT vehicle dimensions.
if nargin<5, R=eye(3); end
T=[R,centre(:);0 0 0 1];
frame=struct('id',"VEHICLE_GLOBAL",'originDescription', ...
    "Midpoint between front contact patches on nominal ground plane",'axisConvention',"X_REAR_Y_RIGHT_Z_UP");
binding=struct('mode',"FIXED",'cornerId',"",'pointIds',strings(0,1));
definition=struct('id',string(id),'componentId',string(id),'componentType',"OTHER", ...
    'role',"OCCUPIED",'frame',frame,'shape',string(shape),'dimensions',dimensions, ...
    'transform',T,'binding',binding,'source',"Analytic synthetic software fixture", ...
    'fidelity',"EXPLICIT_SIMPLIFIED_PRIMITIVE",'sourceRevision',1, ...
    'provenance',"ASSUMED: independent analytic verification, not an FS setup");
volume=fsd.packaging.createVolume(definition,'m');
end
