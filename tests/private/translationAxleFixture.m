function axle = translationAxleFixture(axleId)
%TRANSLATIONAXLEFIXTURE Exact pure-translation double-wishbone benchmark.

if nargin < 1
    axleId = "FRONT";
end
axleId = upper(string(axleId));
if axleId == "FRONT"
    leftId = "FL";
elseif axleId == "REAR"
    leftId = "RL";
else
    error("fsd:test:InvalidAxle", "axleId must be FRONT or REAR.");
end
ids = leftId + "_" + fsd.model.requiredHardpointRoles();
xyz_m = [ ...
    -0.10, -0.30, 0.40; ...
     0.10, -0.30, 0.40; ...
     0.00, -0.60, 0.40; ...
    -0.10, -0.30, 0.10; ...
     0.10, -0.30, 0.10; ...
     0.00, -0.60, 0.10; ...
     0.05, -0.30, 0.25; ...
     0.05, -0.60, 0.25; ...
     0.00, -0.65, 0.25; ...
     0.00, -0.65, 0.00];
provenance = struct( ...
    "sourceKind", repmat("ASSUMED", 10, 3), ...
    "sourceNote", repmat("Exact v0.6 translation benchmark", 10, 3));
left = fsd.model.createDoubleWishboneGeometry( ...
    leftId, ids, xyz_m, "m", [0, -1, 0], provenance);
right = fsd.geometry.reflectDoubleWishboneGeometry(left);
axle = fsd.model.createAxleGeometry(left, right);
end
