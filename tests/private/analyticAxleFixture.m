function axle = analyticAxleFixture(asymmetric)
%ANALYTICAXLEFIXTURE Exact front-view benchmark for v0.4 tests.

if nargin < 1
    asymmetric = false;
end
left = cornerGeometry("FL", [0, -1, 0], [5/12, 1/12]);
right = fsd.geometry.reflectDoubleWishboneGeometry(left);
if asymmetric
    right = setBallJointHeights(right, 11/30, 1/10);
end
axle = fsd.model.createAxleGeometry(left, right);
end

function geometry = cornerGeometry(cornerId, wheelAxis, jointHeights)
ids = cornerId + "_" + fsd.model.requiredHardpointRoles();
xyz_m = [ ...
    -0.100, -0.400, 0.350; ...
     0.100, -0.400, 0.350; ...
     0.000, -0.600, jointHeights(1); ...
    -0.100, -0.400, 0.150; ...
     0.100, -0.400, 0.150; ...
     0.000, -0.600, jointHeights(2); ...
     0.050, -0.400, 0.250; ...
     0.050, -0.570, 0.230; ...
     0.000, -0.650, 0.250; ...
     0.000, -0.650, 0.000];
provenance = struct( ...
    "sourceKind", repmat("ASSUMED", 10, 3), ...
    "sourceNote", repmat("Analytic v0.4 benchmark", 10, 3));
geometry = fsd.model.createDoubleWishboneGeometry( ...
    cornerId, ids, xyz_m, "m", wheelAxis, provenance);
end

function geometry = setBallJointHeights(geometry, ubjZ_m, lbjZ_m)
geometry.hardpoints.xyz_m( ...
    geometry.hardpoints.ids == "FR_UBJ", 3) = ubjZ_m;
geometry.hardpoints.xyz_m( ...
    geometry.hardpoints.ids == "FR_LBJ", 3) = lbjZ_m;
fsd.model.validateDoubleWishboneGeometry(geometry);
end
