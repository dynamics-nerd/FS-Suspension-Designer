function result=antiRollBarSecantResponse(first,second,direction,increment,unit)
%ANTIROLLBARSECANTRESPONSE Incremental secant along an explicitly linear path.
assert(isstruct(first)&&isstruct(second)&&first.available&&second.available&& ...
    isequaln(first.barIdentity,second.barIdentity)&&isnumeric(direction)&&isreal(direction)&&numel(direction)==2&& ...
    all(isfinite(direction))&&isnumeric(increment)&&isreal(increment)&&isscalar(increment)&&isfinite(increment)&& ...
    ismember(string(unit),["m","rad"]),'fsd:analysis:InvalidAntiRollBar','Compatible responses and explicit path required.');
a=double(direction(:)); delta=double(increment); tol=fsd.model.numericTolerances();
assert(all(abs(second.wheelTravel_m-first.wheelTravel_m-a*delta)<=tol.AbsTol_m+tol.RelTol*max(abs(first.wheelTravel_m),1)), ...
    'fsd:analysis:InvalidAntiRollBar','Responses do not lie on the declared modal increment.');
value=NaN; status="ZERO_INCREMENT";
if delta~=0, value=a'*(second.resistance_N-first.resistance_N)/delta; status="AVAILABLE"; end
result=struct('kind',"AntiRollBarSecantResponse",'stiffness',value,'status',status, ...
    'parameterUnit',string(unit),'direction',a,'increment',delta,'firstWheelTravel_m',first.wheelTravel_m, ...
    'secondWheelTravel_m',second.wheelTravel_m);
end
