function modal=antiRollBarModalResponse(response,pathFirst,pathSecond,increment,parameterUnit)
%ANTIROLLBARMODALRESPONSE Explicit path derivatives; no universal roll assumption.
assert(isstruct(response)&&response.kind=="AntiRollBarResponse"&&response.available&& ...
    isnumeric(pathFirst)&&isreal(pathFirst)&&numel(pathFirst)==2&&all(isfinite(pathFirst))&& ...
    isnumeric(pathSecond)&&isreal(pathSecond)&&numel(pathSecond)==2&&all(isfinite(pathSecond))&& ...
    isnumeric(increment)&&isreal(increment)&&(isempty(increment)||(isscalar(increment)&&isfinite(increment)))&& ...
    isscalar(string(parameterUnit))&&ismember(string(parameterUnit),["m","rad"]), ...
    'fsd:analysis:InvalidAntiRollBar','Available response and explicit path derivatives/increment/unit required.');
a=double(pathFirst(:)); b=double(pathSecond(:)); force=a'*response.resistance_N;
tangent=a'*response.tangent_N_per_m*a+response.resistance_N'*b;
candidate=a'*response.candidateTangent_N_per_m*a+response.resistance_N'*b;
% Secant requires a reference response; a single point cannot manufacture it.
modal=struct('kind',"AntiRollBarModalResponse",'parameterUnit',string(parameterUnit), ...
    'pathFirst',a,'pathSecond',b,'increment',double(increment),'generalizedResistance',force, ...
    'tangentStiffness',tangent,'tangentStatus',response.tangentStatus,'candidateTangentStiffness',candidate, ...
    'secantStiffness',NaN,'secantStatus',"REFERENCE_RESPONSE_REQUIRED");
end
