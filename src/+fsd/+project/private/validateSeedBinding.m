function validateSeedBinding(binding)
%VALIDATESEEDBINDING Native construction provenance association, no project recursion.
projectRequire(isstruct(binding) && isscalar(binding) && isequal(sort(string(fieldnames(binding))), ...
    sort(["scenarioId";"projectId";"projectRevision";"construction";"identity"])), 'Invalid seed binding fields.');
fsd.construction.validateParametricSeedResult(binding.construction);
projectRequire(binding.construction.nominalStatus=="VALID" && ...
    ~isempty(regexp(projectText(binding.scenarioId),'^[A-Z][A-Z0-9_]*$','once')) && ...
    ~isempty(regexp(projectText(binding.projectId),'^[A-Z][A-Z0-9_]*$','once')) && ...
    isnumeric(binding.projectRevision) && isscalar(binding.projectRevision) && isfinite(binding.projectRevision) && ...
    binding.projectRevision>=1 && fix(binding.projectRevision)==binding.projectRevision, 'Invalid binding origin.');
identity=struct('scenarioId',binding.scenarioId,'projectId',binding.projectId,'projectRevision',binding.projectRevision, ...
    'constructionIdentity',binding.construction.identity);
projectRequire(isequaln(identity,binding.identity),'Seed binding identity differs.');
end
