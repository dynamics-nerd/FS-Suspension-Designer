function valid=validateSourceCore(source,context)
%VALIDATEPACKAGINGSOURCE Rebuild consumed context/native evidence, no new solve.
fields=["schemaVersion";"kind";"id";"projectId";"projectRevision";"engine";"fsdVersion"; ...
    "sourceIdentity";"dependencySnapshot";"scenarioAtExecution";"prepared";"nativePayload";"assessment";"elapsedTime_s"];
projectRequire(isstruct(source) && isscalar(source) && isequal(sort(string(fieldnames(source))),sort(fields)) && ...
    source.schemaVersion=="0.19.0" && source.kind=="PackagingSourceReference",'Invalid packaging source fields/header.');
plainProjectData(source); snapshot=source.dependencySnapshot;
context.project(snapshot);
projectRequire(isempty(snapshot.definition.results) && isempty(snapshot.definition.derivations) && ...
    ~isfield(snapshot.definition.resources,'packaging') && ...
    ~any(cellfun(@(s)s.definition.engine=="PACKAGING",snapshot.definition.scenarios)), ...
    'Dependency projection must contain no packaging scenarios/resources or historical ledger.');
projectRequire(ismember(source.engine,["BUMP","CORNER_SYNTHESIS","AXLE_SYNTHESIS"]) && ...
    ismember(source.fsdVersion,["0.16.0","0.17.0","0.18.0","0.19.0","0.20.0","0.21.0","0.22.0"]), 'Unsupported native packaging source.');
scenario=scenarioFind(snapshot,source.scenarioAtExecution.definition.id);
projectRequire(isequaln(scenario,source.scenarioAtExecution),'Projected source scenario mismatch.');
p=context.prepare(snapshot,scenario);
projectRequire(p.readiness.status=="READY" && isequaln(p,source.prepared) && source.engine==scenario.definition.engine, ...
    'Projected source preparation/context mismatch.');
expected=struct('schemaVersion',"0.16.0",'id',source.id,'projectId',snapshot.id, ...
    'projectRevision',snapshot.definition.revision,'context',p.context);
projectRequire(source.projectId==snapshot.id && source.projectRevision==snapshot.definition.revision && ...
    isequaln(source.sourceIdentity,expected) && ~isempty(regexp(projectText(source.id),'^[A-Z][A-Z0-9_]*$','once')), ...
    'Original result identity/project/revision differs from dependency evidence.');
assessment=context.payload(p,source.nativePayload);
projectRequire(isequaln(workflowComparable(assessment),workflowComparable(source.assessment)), 'Projected source assessment mismatch.');
projectRequire(isnumeric(source.elapsedTime_s) && isreal(source.elapsedTime_s) && isscalar(source.elapsedTime_s) && ...
    isfinite(source.elapsedTime_s) && source.elapsedTime_s>=0,'Invalid original informational clock.');
valid=true;
end
