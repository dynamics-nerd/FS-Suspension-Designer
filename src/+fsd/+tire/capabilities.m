function c=capabilities(tire)
%CAPABILITIES Family support is distinct from readiness for specific states.
fsd.tire.validate(tire); d=tire.definition;
native=d.force.family=="DUGOFF_REDUCED_1";
c=struct('Fx',native,'Fy',native,'Mz',false,'combinedSlip',native, ...
    'vertical',~isempty(d.geometry.unloadedRadius_m)&&~isempty(d.vertical.stiffness_N_per_m), ...
    'camberThrust',native&&d.force.camberThrust=="LINEAR_CONSTANT", ...
    'camberCapacity',native&&d.force.camberCapacity=="QUADRATIC", ...
    'family',d.force.family,'evidence',d.evidence);
end
