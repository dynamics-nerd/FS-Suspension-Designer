function model=verticalModel(tire,cornerId)
%VERTICALMODEL Adapt only consumed vertical declarations to the historical law.
fsd.tire.validate(tire); d=tire.definition;
assert(~isempty(d.geometry.unloadedRadius_m)&&~isempty(d.vertical.stiffness_N_per_m), ...
    'fsd:tire:MissingVertical','Explicit unloaded radius and vertical stiffness required.');
p=tire.verticalIdentity.provenance; kind="DERIVED";
if p.unloadedRadius_m.sourceKind=="ASSUMED"||p.stiffness_N_per_m.sourceKind=="ASSUMED", kind="ASSUMED"; end
model=fsd.model.createVerticalTireModel(struct('cornerId',string(cornerId),'modelType',"LINEAR_VERTICAL_UNILATERAL", ...
    'stiffness',d.vertical.stiffness_N_per_m,'unloadedRadius',d.geometry.unloadedRadius_m, ...
    'sourceKind',kind,'sourceNote',"Library vertical projection: "+string(jsonencode(p))), ...
    struct('length',"m",'stiffness',"N/m"));
end
