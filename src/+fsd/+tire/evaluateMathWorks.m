function response=evaluateMathWorks(descriptor,states)
%EVALUATEMATHWORKS Optional ISO/SI provider evaluation with explicit channels.
% This is a separate model family, NOT an implementation of DUGOFF_REDUCED_1.
% All eight public tireData inputs must be supplied; no model-derived inputs,
% physical defaults or native sign/slip conversion is supplied. Samples outside
% the provider's declared ranges are rejected; this adapter supports forward
% motion at/above the provider's declared VXLOW, not static/reverse operation.
% Parameters are revalidated against the original .tir using public import.
fields=["schemaVersion","kind","provider","family","variant","coordinateSystem","units", ...
    "sourceFilename","sourceText","parameters","sourceNote","evidence","interpretation","identity"];
assert(isstruct(descriptor)&&isscalar(descriptor)&&all(isfield(descriptor,fields))&& ...
    numel(fieldnames(descriptor))==numel(fields), ...
    'fsd:tire:InvalidMathWorksDescriptor','Canonical MathWorks descriptor required.');
identity=rmfield(descriptor,'identity');
assert(isequaln(identity,descriptor.identity)&&isequal(identity.kind,"MathWorksTireDescriptor")&& ...
    isequal(identity.schemaVersion,"0.22.0")&&isequal(identity.coordinateSystem,"ISO")&&isequal(identity.units,"SI"), ...
    'fsd:tire:InvalidMathWorksDescriptor','Descriptor content/identity mismatch.');
names=["Fz","alpha","kappa","gamma","Vx","IP","psidot","omega"];
assert(isstruct(states)&&isscalar(states)&&all(isfield(states,names))&& ...
    all(ismember(string(fieldnames(states)),names)),'fsd:tire:InvalidMathWorksStates', ...
    'Supply exactly Fz, alpha, kappa, gamma, Vx, IP, psidot and omega in ISO/SI.');
n=1;
for name=names
    value=states.(name);
    assert(isnumeric(value)&&isreal(value)&&isvector(value)&&~isempty(value)&&all(isfinite(value)), ...
        'fsd:tire:InvalidMathWorksStates','Nonempty finite real state vectors required.');
    n=max(n,numel(value));
end
for name=names
    value=double(states.(name));
    assert(isscalar(value)||numel(value)==n,'fsd:tire:InvalidMathWorksStates','State lengths must match or be scalar.');
    if isscalar(value), value=repmat(value,n,1); end
    states.(name)=value(:);
end
assert(all(states.Fz>=0)&&all(states.IP>0),'fsd:tire:InvalidMathWorksStates', ...
    'Nonnegative load and positive absolute pressure required.');
assert(~isempty(which('tireModel'))&&~isempty(which('tireData')), ...
    'fsd:tire:MissingMathWorksTireAPI','Install/enable Extended Tire Features for Vehicle Dynamics Blockset.');
assert(isstring(identity.sourceFilename)&&isscalar(identity.sourceFilename)&& ...
    ~isempty(regexp(identity.sourceFilename,'^[^/\\:]+\.[tT][iI][rR]$','once'))&& ...
    ischar(identity.sourceText)&&isrow(identity.sourceText), ...
    'fsd:tire:InvalidMathWorksDescriptor','Safe .tir filename and original text required.');
folder=string(tempname); mkdir(folder); cleanup=onCleanup(@()removeTemporary(folder));
file=fullfile(folder,identity.sourceFilename);
fid=fopen(file,'w','n','UTF-8');
assert(fid>=0,'fsd:tire:MathWorksTemporaryFile','Cannot create temporary .tir file.');
closer=onCleanup(@()fclose(fid)); fprintf(fid,'%s',identity.sourceText); clear closer;
reconstructed=fsd.tire.importMathWorksTir(file,identity.sourceNote);
assert(isequaln(reconstructed.parameters,identity.parameters)&& ...
    reconstructed.family==identity.family&&reconstructed.variant==identity.variant, ...
    'fsd:tire:InvalidMathWorksDescriptor','Original .tir no longer matches descriptor parameters/family.');
% Reject declared out-of-domain samples before compute can normalize them.
limits={ 'Fz','FZMIN','FZMAX'; 'alpha','ALPMIN','ALPMAX'; ...
    'kappa','KPUMIN','KPUMAX'; 'gamma','CAMMIN','CAMMAX'; 'IP','PRESMIN','PRESMAX'};
for k=1:size(limits,1)
    channel=limits{k,1}; lo=limits{k,2}; hi=limits{k,3};
    p=reconstructed.parameters;
    % MF5.2 has no inflation-pressure sensitivity/range in this provider.
    % The explicit auxiliary channel is not evidence of a pressure model.
    if reconstructed.variant=="MF52"&&strcmp(channel,'IP'), continue; end
    assert(isfield(p,lo)&&isfield(p,hi)&&isscalar(p.(lo))&&isscalar(p.(hi))&& ...
        all(states.(channel)>=p.(lo)&states.(channel)<=p.(hi)), ...
        'fsd:tire:MathWorksOutOfDomain','Samples must satisfy provider-declared %s bounds.',channel);
end
assert(isfield(p,'VXLOW')&&isscalar(p.VXLOW)&&all(states.Vx>=p.VXLOW), ...
    'fsd:tire:MathWorksOutOfDomain','Forward speed must be at/above provider-declared VXLOW.');
model=tireModel.import(file); data=tireData;
assert(string(data.CoordinateSystem)=="ISO",'fsd:tire:MathWorksConvention', ...
    'Provider default contact convention differs from the explicit ISO contract.');
for name=names, data.(name)=states.(name); end
calculated=compute(model,data);
assert(string(calculated.CoordinateSystem)=="ISO",'fsd:tire:MathWorksConvention','Provider returned another convention.');
assert(isnumeric(calculated.Fx)&&isnumeric(calculated.Fy)&& ...
    numel(calculated.Fx)==n&&numel(calculated.Fy)==n, ...
    'fsd:tire:MathWorksResponse','Provider force output dimensions invalid.');
status=repmat("AVAILABLE",n,2);
forces=[calculated.Fx(:),calculated.Fy(:)]; status(~isfinite(forces))="NUMERICALLY_UNRESOLVED";
response=struct('schemaVersion',"0.22.0",'kind',"MathWorksTireResponse", ...
    'modelIdentity',descriptor.identity,'provider',reconstructed.provider, ...
    'importProvider',descriptor.provider,'family',descriptor.family,'variant',descriptor.variant, ...
    'units',"SI",'coordinateSystem',"ISO",'states',states, ...
    'Fx_N',calculated.Fx(:),'Fy_N',calculated.Fy(:),'channels',["Fx","Fy"], ...
    'status',status,'evidence',"IMPORTED_UNVERIFIED", ...
    'diagnostics',"Provider evaluation only; no native convention conversion or predictive validation claimed. MF52 does not model inflation-pressure sensitivity.");
end
function removeTemporary(folder)
% Only the fresh, private temp directory created by this function is removed.
assert(startsWith(folder,string(tempdir),'IgnoreCase',true)&&strlength(folder)>strlength(string(tempdir)), ...
    'fsd:tire:MathWorksTemporaryFile','Cleanup must remain within the temporary directory.');
if isfolder(folder), rmdir(folder,'s'); end
end
