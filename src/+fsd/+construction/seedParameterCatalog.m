function catalog = seedParameterCatalog()
%SEEDPARAMETERCATALOG Explicit scalar decisions; no physical default values.
ids=["WHEEL_EFFECTIVE_RADIUS";"NOMINAL_TOE";"NOMINAL_CAMBER";"UPRIGHT_CLOCKING"; ...
    "UBJ_X";"UBJ_OUTBOARD";"UBJ_Z";"LBJ_X";"LBJ_OUTBOARD";"LBJ_Z"; ...
    "TIE_OUT_X";"TIE_OUT_OUTBOARD";"TIE_OUT_Z"; ...
    "UCA_CENTER_X";"UCA_LATERAL";"UCA_HEIGHT";"UCA_SPAN";"UCA_LATERAL_DELTA";"UCA_HEIGHT_DELTA"; ...
    "LCA_CENTER_X";"LCA_LATERAL";"LCA_HEIGHT";"LCA_SPAN";"LCA_LATERAL_DELTA";"LCA_HEIGHT_DELTA"; ...
    "TIE_IN_X";"TIE_IN_LATERAL";"TIE_IN_HEIGHT"];
catalog=repmat(struct('id',"",'quantity',"LENGTH",'unit',"m",'requirement',"REQUIRED", ...
    'reference',"",'positive',false,'dependencies',strings(0,1)),numel(ids),1);
for j=1:numel(ids)
    q="LENGTH"; unit="m"; if ismember(j,2:4), q="ANGLE"; unit="rad"; end
    ref="CONTACT_DATUM_AND_VEHICLE_AXES";
    if ismember(j,5:13), ref="WHEEL_CENTER_UPRIGHT_REFERENCE"; end
    if j<=4, ref="WHEEL_AND_UPRIGHT_ORIENTATION"; end
    catalog(j)=struct('id',ids(j),'quantity',q,'unit',unit,'requirement',"REQUIRED", ...
        'reference',ref,'positive',ismember(j,[1,15,17,21,23,27]),'dependencies',strings(0,1));
end
end
