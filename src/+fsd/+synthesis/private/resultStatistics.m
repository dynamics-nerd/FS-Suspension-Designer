function stats = resultStatistics(search,elapsed)
%RESULTSTATISTICS Transparent counters and separated wall-time diagnostics.
records=search.records; timing=zeros(numel(records),5);
for i=1:numel(records)
    t=records{i}.timing_s; timing(i,:)=[t.builder,t.solver,t.analysis,t.evaluator,t.total];
end
stats=struct('uniqueEvaluations',search.evaluationCount,'attempts',search.attemptCount, ...
    'cacheHits',search.cacheHitCount,'physicalBumpSweeps',sum(cellfun(@(e) e.solverCalls,records)), ...
    'validGeometries',sum(cellfun(@(e) e.geometryValid,records)), ...
    'eligibleCandidates',numel(search.eligibleIndices), ...
    'builder_s',sum(timing(:,1)),'solver_s',sum(timing(:,2)),'analysis_s',sum(timing(:,3)), ...
    'evaluator_s',sum(timing(:,4)),'controllerOverhead_s',elapsed-sum(timing(:,5)));
end
