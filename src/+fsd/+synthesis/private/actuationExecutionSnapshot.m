function snapshot = actuationExecutionSnapshot(space)
%ACTUATIONEXECUTIONSNAPSHOT Immutable physical and numerical context, before solves.
mechanical=[]; if ~isempty(space.seedMechanical), mechanical=space.seedMechanical.identity; end
snapshot=struct('schemaVersion',"0.15.0",'kind',"ActuationSynthesisExecutionSnapshot", ...
    'suspensionIdentity',space.seedIdentity,'referenceFrame',space.seed.referenceFrame, ...
    'actuationIdentity',space.seedActuation.identity,'mechanicalIdentity',mechanical, ...
    'specificationIdentity',space.specification.identity,'plan',space.plan,'sourceIds',{space.sourceIds}, ...
    'variables',{space.variables},'dependentAxisComponent',space.dependentAxisComponent, ...
    'numericalTolerances',fsd.model.numericTolerances());
end
