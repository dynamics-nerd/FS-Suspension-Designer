function snapshot = axleExecutionSnapshot(space)
%AXLEEXECUTIONSNAPSHOT Immutable execution context captured before any solve.
snapshot=struct('schemaVersion',"0.13.0",'kind',"AxleSynthesisExecutionSnapshot", ...
    'seedIdentity',space.seedIdentity,'referenceFrame',space.seedAxle.leftGeometry.referenceFrame, ...
    'specificationIdentity',space.specification.identity,'plan',space.plan,'sourceIds',{space.sourceIds}, ...
    'physicalVariables',{space.physicalVariables},'variables',{space.variables}, ...
    'symmetryLinks',space.symmetryLinks,'independentIndex',space.independentIndex,'multiplier',space.multiplier);
end
