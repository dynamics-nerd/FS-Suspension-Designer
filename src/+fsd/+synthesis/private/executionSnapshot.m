function snapshot = executionSnapshot(space)
%EXECUTIONSNAPSHOT Canonical execution inputs, captured before physical work.
snapshot=struct('kind',"SynthesisExecutionSnapshot",'schemaVersion',"0.12.0", ...
    'seedIdentity',space.seedIdentity,'specificationIdentity',space.specification.identity, ...
    'sourceIds',space.sourceIds,'travel_m',space.plan.travel_m, ...
    'solverOptions',fsd.kinematics.solverSettings(space.plan.solverOptions));
end
