function definition=antiRollBarInputs(representation,axleId)
%ANTIROLLBARINPUTS Explicit synthetic software declarations, never FS advice.
if nargin<1, representation="EQUIVALENT_LINEAR"; end
if nargin<2, axleId="FRONT"; end
p=struct('weights',[-1;1],'linearStiffness_N_per_m',10000, ...
    'installationWheelTravel_m',[0;0],'wheelTravelDomain_m',[-.05,.05;-.05,.05], ...
    'deflectionDomain_m',[-.1,.1]);
definition=struct('id',"SYNTHETIC_ARB",'axleId',string(axleId),'representation',string(representation), ...
    'referenceMode',"ZERO_AT_INSTALLATION",'parameters',p,'provenance',struct(), ...
    'note',"Synthetic software benchmark; not measured or recommended FS data.");
if string(representation)=="COAXIAL_TORSION"
    % Reference geometry has arms in +X and vertical links to synthetic pickups.
    p=struct('axisPoint_m',[0,0,0],'axisDirection_unit',[0,1,0], ...
        'supports_m',[0,-.3,0;0,.3,0],'armPoints_m',[.1,-.5,0;.1,.5,0], ...
        'driverPoints_m',[.1,-.5,-.2;.1,.5,-.2],'linkLengths_m',[.2;.2], ...
        'installationAngles_rad',[.1;.3],'kTheta_Nm_per_rad',100, ...
        'wheelTravelDomain_m',[-.05,.05;-.05,.05],'armAngleDomain_rad',[-1,1;-1,1], ...
        'twistDomain_rad',[-1,1]);
    definition.parameters=p; definition.drivers=["UPRIGHT";"UPRIGHT"];
    definition.stiffnessMode="KNOWN"; definition.stiffnessScope="SHAFT_ONLY";
    definition.referenceFrame=struct('id',"SYNTHETIC_ARB_FRAME",'originDescription',"Explicit synthetic mechanism origin", ...
        'axisConvention',"X_REAR_Y_RIGHT_Z_UP");
end
for key=string(fieldnames(definition.parameters))'
    definition.provenance.(key)=struct('sourceKind',"ASSUMED",'sourceNote',"Synthetic software benchmark only");
end
end
