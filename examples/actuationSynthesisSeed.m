function [geometry,actuation,mechanical,definition,mechanicalDefinition,units] = actuationSynthesisSeed(architecture,corner)
%ACTUATIONSYNTHESISSEED ASSUMED illustrative data, not a validated FS vehicle.
% Separate PUSHROD upper rocker and PULLROD lower rocker configurations.
% Rod axial force, bearing/bracket locations and structural safety are not inferred.
if nargin<1, architecture="PUSHROD"; end
if nargin<2, corner="FL"; end
corner=string(corner); architecture=string(architecture);
if ~ismember(corner,["FL","FR","RL","RR"]) || ~ismember(architecture,["PUSHROD","PULLROD"])
    error('fsd:examples:InvalidActuationSeed','Explicit supported corner and architecture required.');
end
xyz=[-.10,-.30,.40;.10,-.30,.40;0,-.60,.40; ...
    -.10,-.30,.10;.10,-.30,.10;0,-.60,.10; ...
    .05,-.30,.25;.05,-.60,.25;0,-.65,.25;0,-.65,0];
side=1; if ismember(corner,["FR","RR"]), side=-1; end
rear=0; if ismember(corner,["RL","RR"]), rear=1.6; end % ASSUMED example rear station [m]
xyz(:,1)=xyz(:,1)+rear; xyz(:,2)=side*xyz(:,2);
provenance=struct('sourceKind',repmat("ASSUMED",10,3), ...
    'sourceNote',repmat("Illustrative analytic geometry; arm radius 0.3 m; not FS recommendations",10,3));
geometry=fsd.model.createDoubleWishboneGeometry(corner,corner+"_"+fsd.model.requiredHardpointRoles(), ...
    xyz,'m',[0,-side,0],provenance);
if architecture=="PUSHROD"
    pivot=[0,-.30,.40]; rod=[0,-.40,.40]; damper=[0,-.30,.30]; chassis=[.12,-.38,.34];
else
    pivot=[0,-.30,.10]; rod=[0,-.40,.10]; damper=[0,-.30,.20]; chassis=[.12,-.22,.16];
end
points=[pivot;rod;damper;chassis;0,-.50,.25];
points(:,1)=points(:,1)+rear; points(:,2)=side*points(:,2);
definition=struct('actuationType',architecture, ...
    'suspensionAttachment',struct('body',"UPRIGHT",'point',points(5,:)), ...
    'rocker',struct('orientationMode',"YZ_PLANE",'axis',struct('point',points(1,:)), ...
    'actuationRodPoint',points(2,:),'damperPoint',points(3,:)), ...
    'damper',struct('chassisPoint',points(4,:)), ...
    'metadata',struct('sourceKind',"ASSUMED",'sourceNote', ...
    "Illustrative distinct upper/lower rocker designs; no rod-force or packaging certification"));
actuation=fsd.model.createActuationGeometry(geometry,definition,'m');
mechanicalDefinition=struct('configuration',"COILOVER", ...
    'spring',struct('modelType',"LINEAR_COMPRESSION",'rate',30000,'freeLength',.20,'preloadCompression',.02), ...
    'damper',struct('modelType',"LINEAR_ASYMMETRIC",'compressionCoefficient',1500,'reboundCoefficient',2500), ...
    'metadata',struct('sourceKind',"ASSUMED",'sourceNote', ...
    "Test-only 30000 N/m, 0.20 m free length, 0.02 m preload, 1500/2500 N*s/m; no hardware limits inferred"));
units=struct('length',"m",'springRate',"N/m",'dampingCoefficient',"N*s/m",'velocity',"m/s");
mechanical=fsd.model.createSpringDamperModel(actuation,mechanicalDefinition,units);
end
