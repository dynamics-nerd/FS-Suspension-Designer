function [project,definition]=globalStaticGuidedInputs()
%GLOBALSTATICGUIDEDINPUTS Explicit synthetic four-corner software benchmark only.
% Not loaded by the UI automatically. Independent nominal closure derivative
% sets Fs*MR=500 N at z=0; M=200 kg, g=10, R0=.25, kt=100000.
ids=["FL","FR","RL","RR"]; gs=cell(4,1); acts=gs; ms=gs; tires=gs; plans=struct();
for k=1:4
    id=ids(k); [g,a,~,~,md,units]=actuationSynthesisSeed('PUSHROD',id);
    % d(|rod-attachment|^2)/dz=0 and c=-dL, at nominal pure vertical WC motion.
    axis=a.rocker.axis.direction_unit; pivot=a.rocker.axis.point_m;
    rod=a.rocker.actuationRodPoint.pointStatic_m; damper=a.rocker.damperPoint.pointStatic_m;
    attachment=a.suspensionAttachment.pointStatic_m; chassis=a.damper.chassisPoint.point_m;
    v=rod-attachment; thetaPrime=dot(v,[0,0,1])/dot(v,cross(axis,rod-pivot));
    mr=-dot(damper-chassis,cross(axis,damper-pivot))/norm(damper-chassis)*thetaPrime;
    md.spring.preloadCompression=500/(md.spring.rate*mr);
    md.metadata.sourceNote="DERIVED software benchmark preload: 500/(ks*MRnominal), analytic closure derivative; not FS data";
    gs{k}=g; acts{k}=a; ms{k}=fsd.model.createSpringDamperModel(a,md,units);
    tires{k}=fsd.model.createVerticalTireModel(struct('cornerId',id,'modelType',"LINEAR_VERTICAL_UNILATERAL", ...
        'stiffness',100000,'unloadedRadius',.25,'sourceKind',"ASSUMED",'sourceNote',"Synthetic independent benchmark"), ...
        struct('length',"m",'stiffness',"N/m"));
    plans.(id)=struct('travel_m',(-.02:.002:.02)','wheelVelocity_m_per_s',0);
end
names=["VEHICLE_MASS","WHEELBASE","FRONT_TRACK","REAR_TRACK","CG_X","CG_Y","CG_Z", ...
    "UNSPRUNG_MASS_FL","UNSPRUNG_MASS_FR","UNSPRUNG_MASS_RL","UNSPRUNG_MASS_RR"];
values=[200,1.6,1.3,1.3,.8,0,.3,0,0,0,0]; ps=cell(numel(names),1);
for k=1:numel(names)
    unit="m"; if contains(names(k),'MASS'), unit="kg"; end
    ps{k}=fsd.project.createConceptParameter(names(k),struct('value',values(k),'availability',"ASSUMED", ...
        'sourceKind',"ASSUMED",'sourceNote',"Synthetic software benchmark; no real vehicle data"),unit);
end
concept=fsd.project.createVehicleConcept(struct('id',"GLOBAL_GUIDED_EXAMPLE", ...
    'massConvention',"INCLUDES_DRIVER",'parameters',{ps}));
project=fsd.project.createEngineeringProject(struct('concept',concept,'resources', ...
    struct('geometries',{gs},'actuations',{acts},'mechanicals',{ms})));
vo=struct('gravity_mps2',10,'gravitySourceKind',"ASSUMED",'gravitySourceNote',"Synthetic g=10 benchmark", ...
    'operatingConfiguration',"SOFTWARE_BENCHMARK",'contactPolicy',"CONCEPTUAL_HORIZONTAL", ...
    'contactSourceKind',"ASSUMED",'contactSourceNote',"Explicit rectangular nominal references; actual WC comes from solves");
so=struct('massApproximation',"KNOWN_UNSPRUNG_MASSES", ...
    'unsprungPositionAssumption',"UNSPRUNG_MASS_AT_WHEEL_CENTER",'roadHeight_m',0, ...
    'rideHeightPointsBody_m',[.8,0,.1],'rideHeightPointIds',"CHASSIS_REFERENCE");
options=struct('bounds',[-.03,.03;-.05,.05;-.05,.05;repmat([-.015,.015],4,1)], ...
    'coordinateScales',[.01;.02;.02;repmat(.01,4,1)],'forceTolerance_N',1e-5, ...
    'momentTolerance_Nm',1e-6,'positionTolerance_m',1e-9,'angleTolerance_rad',1e-9,'stabilityTolerance_J',1e-8);
definition=struct('id',"UI_GLOBAL_STATIC",'engine',"GLOBAL_STATIC", ...
    'scope',fsd.model.designScope('VEHICLE','VEHICLE'),'inputs',struct('tires',{tires}), ...
    'plan',struct('vehicleOptions',vo,'systemOptions',so,'cornerPlans',plans,'initialGuesses',[-.005;zeros(6,1)]), ...
    'options',options);
end
